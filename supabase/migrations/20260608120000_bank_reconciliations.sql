grant select, insert, update, delete on public.bank_statement_lines to authenticated;
grant select, insert, update, delete on public.reconciliations to authenticated;
grant select, insert, update, delete on public.reconciliation_lines to authenticated;

grant all on public.bank_statements to service_role;
grant all on public.bank_statement_lines to service_role;
grant all on public.reconciliations to service_role;
grant all on public.reconciliation_lines to service_role;

grant execute on function public.sum_reconciliation_matched_amount(uuid) to authenticated;
grant execute on function public.sum_reconciliation_matched_amount(uuid) to service_role;

grant execute on function public.count_bank_lines_by_match_status(uuid, text) to authenticated;
grant execute on function public.count_bank_lines_by_match_status(uuid, text) to service_role;
